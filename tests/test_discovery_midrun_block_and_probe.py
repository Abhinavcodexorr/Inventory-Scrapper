"""Three ways discovery used to misjudge a supportable site.

  * driftmotors.ca / tabangimotors.com: the WAF starts refusing part-way
    through discovery (CloudFront 403, Cloudflare 429). The final selector check
    then ran against the block page, found no vehicle links, and blamed the
    layout. A block must be reported as a block.
  * clutch.ca: its grid calls page=0 on load and page=1, 2 on scroll. Diffing
    the scroll calls gave start=1, skipping the first page every sync; and the
    page-2 fallback probe sent "InventoryBot", which clutch's WAF refuses, so
    pagination looked unprovable.
  * clutch.ca's captured headers carried a minutes-lived x-aws-waf-token and
    per-request tracing ids, frozen into scrape_config.

Run:  python -m pytest tests/test_discovery_midrun_block_and_probe.py
"""
from __future__ import annotations

import json

from dealer_scraper.adapters import blocking
from dealer_scraper.config import settings
from dealer_scraper.discovery.context import Candidate, CandidateKind, DiscoveryContext
from dealer_scraper.discovery.decision import DecisionEngine
from dealer_scraper.discovery.heuristics import DEFAULT_HEURISTICS
from dealer_scraper.discovery.coordinator import _current_page_block
from dealer_scraper.discovery.net import pagination_probe
from dealer_scraper.discovery.net.pagination_probe import (
    _detect_pagination,
    _probe_pagination_via_http,
)
from dealer_scraper.discovery.net.scorer import _extra_request_headers

API = "https://api.example.com/v1/vehicles?downPayment=0"


class _Page:
    def __init__(self, title: str, body: str, url: str = "https://dealer.example.com/used"):
        self._title, self._body, self.url = title, body, url

    def title(self):
        return self._title

    def text_content(self, _sel):
        return self._body


def _ctx(status: int | None, url: str = "https://dealer.example.com/used") -> DiscoveryContext:
    ctx = DiscoveryContext(base_url="https://dealer.example.com", host="dealer.example.com")
    if status is not None:
        ctx.snapshots["last_document"] = {"url": url, "status": status, "headers": {}}
    return ctx


def test_unbranded_403_after_navigation_is_a_block():
    # CloudFront's error page names no vendor; only the status says "refused".
    page = _Page("ERROR: The request could not be satisfied", "403 ERROR Request blocked.")
    assert _current_page_block(page, _ctx(403)).blocked


def test_cloudflare_challenge_title_is_a_block():
    page = _Page("Just a moment...", "")
    assert _current_page_block(page, _ctx(None)).blocked


def test_healthy_listing_is_not_a_block():
    page = _Page("Used Cars | Dealer", "2021 Honda Civic $21,995 45,000 km")
    assert not _current_page_block(page, _ctx(200)).blocked


def test_cloudfront_error_page_is_a_block_without_status():
    page = _Page("ERROR: The request could not be satisfied",
                 "403 ERROR The request could not be satisfied. Generated by cloudfront (CloudFront)")
    assert _current_page_block(page, _ctx(None)).blocked


def test_dropped_navigation_is_a_block():
    page = _Page("", "This site can't be reached", url="chrome-error://chromewebdata/")
    assert _current_page_block(page, _ctx(200, url="https://dealer.example.com/")).blocked


def test_stale_status_from_another_page_is_ignored():
    # A 403 recorded for some other URL says nothing about the page shown now.
    page = _Page("Used Cars | Dealer", "2021 Honda Civic $21,995 45,000 km")
    assert not _current_page_block(page, _ctx(403, url="https://dealer.example.com/other")).blocked


def test_detect_pagination_starts_at_lowest_observed_page():
    urls = [f"{API}&page=1", f"{API}&page=2", f"{API}&page=0"]
    info = _detect_pagination(urls)
    assert info["param"] == "page"
    assert info["start"] == 0
    assert info["step"] == 1


def test_detect_pagination_ignores_lower_value_off_the_step_grid():
    urls = [f"{API}&offset=20", f"{API}&offset=40", f"{API}&offset=5"]
    info = _detect_pagination(urls)
    assert info["start"] == 20


class _Resp:
    def __init__(self, status: int, body: dict | None = None):
        self.status_code = status
        self.headers = {"content-type": "application/json"}
        self._body = body

    def json(self):
        return self._body


def _fake_client(seen: list):
    """Zero-based paged API behind a WAF that refuses non-browser UAs."""
    class _Client:
        def __init__(self, timeout=None, headers=None):
            self.headers = headers or {}

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

        def get(self, url):
            seen.append((url, self.headers.get("User-Agent")))
            if "InventoryBot" in (self.headers.get("User-Agent") or ""):
                return _Resp(403)
            page = int(url.rsplit("page=", 1)[1]) if "page=" in url else 0
            return _Resp(200, {"vehicles": [{"id": page * 100 + i} for i in range(3)]})
    return lambda timeout=10, headers=None: _Client(timeout, headers)


def test_probe_uses_sync_user_agent_and_observed_start_page(monkeypatch):
    seen: list = []
    monkeypatch.setattr(pagination_probe, "safe_client", _fake_client(seen))
    first = [{"id": i} for i in range(3)]
    info = _probe_pagination_via_http(f"{API}&page=0", "vehicles", first)
    assert info is not None
    assert info["param"] == "page" and info["start"] == 0
    assert "page={page}" in info["template_url"]
    assert seen[0] == (f"{API}&page=1", settings.scraper_user_agent)


def test_probe_without_observed_page_asks_for_page_two(monkeypatch):
    seen: list = []
    monkeypatch.setattr(pagination_probe, "safe_client", _fake_client(seen))
    first = [{"id": i} for i in range(3)]
    info = _probe_pagination_via_http(API, "vehicles", first)
    assert info["start"] == 1
    assert seen[0][0] == f"{API}&page=2"


def test_zero_based_start_page_survives_config_build():
    cand = Candidate(
        key="api:api.example.com/v1/vehicles", kind=CandidateKind.JSON_API, url=API,
        draft={"endpoint": f"{API}&page={{page}}", "list_path": "vehicles",
               "field_map": {"external_id": "id", "make": "make", "model": "model", "year": "year"},
               "page_size": 32, "start_page": 0, "total_path": "totalCount"},
    )
    config = DecisionEngine(DEFAULT_HEURISTICS).build_config("json_api", cand)
    assert config["start_page"] == 0


class _Route:
    """Playwright route stand-in: fetch() replays `statuses` in order."""

    def __init__(self, url: str, rtype: str, statuses: list[int]):
        self.request = type("R", (), {"url": url, "resource_type": rtype})()
        self._statuses = list(statuses)
        self.fetches = 0
        self.outcome = None

    def fetch(self, max_redirects=None):
        assert max_redirects == 0   # redirects go back through the guarded route
        self.fetches += 1
        return type("Resp", (), {"status": self._statuses.pop(0)})()

    def fulfill(self, response):
        self.outcome = ("fulfill", response.status)

    def continue_(self):
        self.outcome = ("continue", None)


def test_paced_fetch_retries_a_refused_site_script(monkeypatch):
    # sm360: the inventory script answers 429 when requested in a burst.
    monkeypatch.setattr(blocking.time, "sleep", lambda s: None)
    route = _Route("https://www.dealer.example.com/js/dynamic-inventory.min.js", "script", [429, 200])
    blocking.continue_paced(route, "dealer.example.com")
    assert route.outcome == ("fulfill", 200) and route.fetches == 2


def test_paced_fetch_leaves_other_hosts_and_types_to_the_browser(monkeypatch):
    monkeypatch.setattr(blocking.time, "sleep", lambda s: None)
    other = _Route("https://cdn.vendor.com/lib.js", "script", [200])
    blocking.continue_paced(other, "dealer.example.com")
    assert other.outcome == ("continue", None) and other.fetches == 0
    xhr = _Route("https://dealer.example.com/api/listing", "xhr", [200])
    blocking.continue_paced(xhr, "dealer.example.com")
    assert xhr.outcome == ("continue", None) and xhr.fetches == 0


def test_extra_headers_drop_waf_token_and_tracing_ids():
    captured = {
        "origin": "https://www.clutch.ca",
        "x-api-key": "abc123",
        "x-aws-waf-token": "3023fb93:CAoAdl+GUEO2FgAA:0Nhco",
        "traceparent": "00-0000-01",
        "tracestate": "dd=s:1",
        "x-datadog-trace-id": "165495",
        "x-datadog-origin": "rum",
    }
    assert json.dumps(_extra_request_headers(captured), sort_keys=True) == json.dumps(
        {"origin": "https://www.clutch.ca", "x-api-key": "abc123"}, sort_keys=True)


